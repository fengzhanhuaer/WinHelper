#include "tab_quickaction.h"

#include <windows.h>
#include <shellapi.h>

#include "imgui.h"

// ---------------------------------------------------------------------------
// Internal helper
// ---------------------------------------------------------------------------
static void OpenTarget(const wchar_t* target) {
    ShellExecuteW(nullptr, L"open", target, nullptr, nullptr, SW_SHOWNORMAL);
}

// ---------------------------------------------------------------------------
// Public
// ---------------------------------------------------------------------------
void RenderTabQuickAction() {
    if (!ImGui::BeginTabItem("\xe5\xbf\xab\xe9\x80\x9f\xe6\x93\x8d\xe4\xbd\x9c")) // 快速操作
        return;

    ImGui::TextUnformatted("\xe5\xb8\xb8\xe7\x94\xa8\xe5\x85\xa5\xe5\x8f\xa3\xef\xbc\x9a"); // 常用入口：

    if (ImGui::Button("\xe6\x89\x93\xe5\xbc\x80\xe6\x8e\xa7\xe5\x88\xb6\xe9\x9d\xa2\xe6\x9d\xbf")) // 打开控制面板
        OpenTarget(L"control.exe");
    ImGui::SameLine();
    if (ImGui::Button("\xe6\x89\x93\xe5\xbc\x80\xe4\xbb\xbb\xe5\x8a\xa1\xe7\xae\xa1\xe7\x90\x86\xe5\x99\xa8")) // 打开任务管理器
        OpenTarget(L"taskmgr.exe");

    if (ImGui::Button("\xe6\x89\x93\xe5\xbc\x80 Windows \xe8\xae\xbe\xe7\xbd\xae")) // 打开 Windows 设置
        OpenTarget(L"ms-settings:");
    ImGui::SameLine();
    if (ImGui::Button("\xe6\x89\x93\xe5\xbc\x80\xe8\xae\xbe\xe5\xa4\x87\xe7\xae\xa1\xe7\x90\x86\xe5\x99\xa8")) // 打开设备管理器
        OpenTarget(L"devmgmt.msc");

    ImGui::Spacing();
    ImGui::TextWrapped(
        "\xe5\x90\x8e\xe7\xbb\xad\xe5\x8f\xaf\xe5\x9c\xa8\xe8\xbf\x99\xe9\x87\x8c\xe6\x89\xa9\xe5\xb1\x95\xef\xbc\x9a"
        "\xe6\x9c\x8d\xe5\x8a\xa1\xe7\xae\xa1\xe7\x90\x86\xe3\x80\x81\xe7\xbd\x91\xe7\xbb\x9c\xe8\xaf\x8a\xe6\x96\xad"
        "\xe3\x80\x81\xe5\x90\xaf\xe5\x8a\xa8\xe9\xa1\xb9\xe4\xbc\x98\xe5\x8c\x96\xe3\x80\x81\xe6\x96\x87\xe4\xbb\xb6"
        "\xe6\xb8\x85\xe7\x90\x86\xe7\xad\x89\xe3\x80\x82\n"
        "\xe5\xbd\x93\xe5\x89\x8d\xe7\x89\x88\xe6\x9c\xac\xe8\x81\x9a\xe7\x84\xa6\xe5\x9f\xba\xe7\xa1\x80\xe6\xa1\x86"
        "\xe6\x9e\xb6\xe4\xb8\x8e\xe5\xb8\xb8\xe7\x94\xa8\xe5\x85\xa5\xe5\x8f\xa3\xe6\x95\xb4\xe5\x90\x88\xe3\x80\x82");

    ImGui::EndTabItem();
}
